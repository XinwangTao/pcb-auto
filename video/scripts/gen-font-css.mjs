#!/usr/bin/env node
/**
 * gen-font-css.mjs — 把 public/fonts 下的 TTF 转成内联 base64 的 @font-face CSS。
 *
 * 为什么内联而不是 staticFile() + FontFace：
 * Remotion 并行开多个 page 渲染，靠 URL 拉字体时部分 page 的请求会挂住，
 * 导致模块层的 delayRender 超时（实测 3480 帧里跑到 442 帧就炸）。
 * 内联成 data URI 后浏览器解析 CSS 即可拿到字体，不依赖任何网络/静态服务。
 *
 * 产物：src/fonts.css（由本脚本生成，勿手改）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const VIDEO = path.resolve(__dirname, '..');
const FONTS = path.join(VIDEO, 'public', 'fonts');

const FACES = [
  { family: 'YaHei', file: 'sub-regular.ttf', weight: 400 },
  { family: 'YaHei', file: 'sub-bold.ttf', weight: 700 },
  { family: 'ConsolaLocal', file: 'sub-mono.ttf', weight: 400 },
  { family: 'ConsolaLocal', file: 'sub-monob.ttf', weight: 700 },
];

let out = '/* AUTO-GENERATED by scripts/gen-font-css.mjs — do not edit */\n';
let total = 0;

for (const { family, file, weight } of FACES) {
  const p = path.join(FONTS, file);
  if (!fs.existsSync(p)) {
    console.warn(`[gen-font-css] missing ${file}, skipped`);
    continue;
  }
  const b64 = fs.readFileSync(p).toString('base64');
  total += b64.length;
  out += `@font-face{font-family:'${family}';src:url(data:font/ttf;base64,${b64}) format('truetype');font-weight:${weight};font-style:normal;font-display:block;}\n`;
  console.log(`[gen-font-css] ${family} ${weight} <- ${file} (${(b64.length / 1024).toFixed(0)} KB b64)`);
}

const dest = path.join(VIDEO, 'src', 'fonts.css');
fs.writeFileSync(dest, out, 'utf8');
console.log(`[gen-font-css] wrote ${path.relative(VIDEO, dest)} (${(total / 1024).toFixed(0)} KB)`);
